export function FaqSection() {
  const [openIndex, setOpenIndex] = useState<number | null>(0);

  function toggle(i: number, willOpen: boolean) {
    setOpenIndex(willOpen ? i : null);
    if (willOpen) trackCtaEvent('faq_click');
  }

  return (
    <Section id="faq">
      <Container>
        <SectionHeading center title="Вопросы и ответы" />

        <div className="mx-auto mt-10 max-w-3xl divide-y divide-slate-200 rounded-2xl border border-slate-200 bg-white">
          {FAQ_ITEMS.map((item, i) => {
            const open = openIndex === i;
            return (
              <div key={item.q}>
                <button
                  type="button"
                  onClick={() => toggle(i, !open)}
                  aria-expanded={open}
                  data-cta-event="faq_click"
                  className="flex w-full items-center justify-between gap-4 px-6 py-5 text-left focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-blue-500 focus-visible:ring-inset"
                >
                  <span className="font-medium text-slate-900">{item.q}</span>
                  <ChevronDown
                    className={cn('h-5 w-5 shrink-0 text-slate-400 transition-transform', open && 'rotate-180')}
                    aria-hidden
                  />
                </button>
                {open && <p className="px-6 pb-5 leading-relaxed text-slate-600">{item.a}</p>}
              </div>
            );
          })}
        </div>
      </Container>
    </Section>
  );
}
